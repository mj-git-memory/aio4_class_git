def connect(path: Path):
    # 기존 호출과 호환되도록 path를 받지만, Supabase에서는 사용하지 않습니다.
    return psycopg.connect(
        **load_db_config(),
        sslmode="require",
        connect_timeout=10,
        row_factory=dict_row,
    )


