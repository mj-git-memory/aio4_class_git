def list_entries(path: Path, page: int):
    with closing(connect(path)) as db:
        # SQLite: total = db.execute("SELECT COUNT(*) FROM entries").fetchone()[0]
        total = db.execute("SELECT COUNT(*) AS total FROM guestbook.entries").fetchone()["total"]
        pages = max(1, (total + PAGE_SIZE - 1) // PAGE_SIZE)
        page = min(page, pages)
        rows = db.execute(
            # SQLite: SELECT id, name, message, created_at FROM entries ORDER BY id DESC LIMIT ? OFFSET ?
            "SELECT id, name, message, created_at FROM guestbook.entries ORDER BY id DESC LIMIT %s OFFSET %s",
            (PAGE_SIZE, (page - 1) * PAGE_SIZE),
        ).fetchall()
    return rows, total, page, pages


def add_entry(path: Path, name: str, message: str, password: str):
    password_hash = hash_password(password)
    with closing(connect(path)) as db, db:
        # 개수 확인과 저장을 같은 쓰기 트랜잭션에서 처리한다.
        # SQLite: db.execute("BEGIN IMMEDIATE")
        db.execute("LOCK TABLE guestbook.entries IN EXCLUSIVE MODE")
        # SQLite: total = db.execute("SELECT COUNT(*) FROM entries").fetchone()[0]
        total = db.execute("SELECT COUNT(*) AS total FROM guestbook.entries").fetchone()["total"]
        if total >= MAX_ENTRIES:
            raise ValueError("방명록이 가득 찼습니다. 관리자에게 문의해 주세요.")
        # 문자열을 SQL에 직접 이어 붙이지 않고 값 자리(%s)에 전달한다.
        db.execute(
            # SQLite: INSERT INTO entries (name, message, created_at, password_hash) VALUES (?, ?, ?, ?)
            "INSERT INTO guestbook.entries (name, message, created_at, password_hash) VALUES (%s, %s, %s, %s)",
            (name, message, datetime.now(KST).isoformat(timespec="minutes"), password_hash),
        )


def get_entry(path: Path, entry_id: int):
    with closing(connect(path)) as db:
        # SQLite: return db.execute("SELECT * FROM entries WHERE id = ?", (entry_id,)).fetchone()
        return db.execute("SELECT * FROM guestbook.entries WHERE id = %s", (entry_id,)).fetchone()


def update_entry(path: Path, entry_id: int, name: str, message: str, password: str):
    entry = get_entry(path, entry_id)
    if entry is None:
        raise LookupError("방명록을 찾을 수 없습니다.")
    if not entry["password_hash"]:
        raise PermissionError("비밀번호 기능 추가 전에 작성된 글은 수정할 수 없습니다.")
    if not verify_password(password, entry["password_hash"]):
        raise PermissionError("비밀번호가 일치하지 않습니다.")
    with closing(connect(path)) as db, db:
        db.execute(
            # SQLite: UPDATE entries SET name = ?, message = ? WHERE id = ?
            "UPDATE guestbook.entries SET name = %s, message = %s WHERE id = %s",
            (name, message, entry_id),
        )
