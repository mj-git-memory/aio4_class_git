### 레디스(Redis) : 데이터를 메모리(RAM)에 저장해서 빠르게 읽고 쓰는 데이터 저장소
# -> 여러 프로그램이 함께 사용하는, 아주 빠르고 유효기간도 설정할 수 있는 저장소
# -> 데이터를 키(key)와 값(value) 형태로 저장
# 키                   값
# user:1:name        "홍길동"
# product:10:stock    50
# -> **유효기간(TTL)**도 설정할 수 있음
# SET auth:1234 "987654" EX 180 : → auth:1234라는 키에 인증번호를 저장하고 180초 뒤 자동 삭제
# -> 별도의 서버로 실행되기 때문에 여러 프로그램이 같은 데이터를 공유할 수 있음 

# 어디에 쓰나요?
# - 캐시: 자주 조회하는 데이터를 잠시 저장해서 응답 속도를 높임
# - 로그인 세션: 로그인 상태를 여러 서버에서 공유
# - 인증번호: 문자 인증번호를 저장하고 3분 뒤 자동 삭제
# - 실시간 순위: 게임 점수나 인기 순위 관리
# ex) FastAPI에서 상품 정보를 조회한다면:
# 사용자 → FastAPI → Redis에 상품 정보가 있나?
#                    ├─ 있으면 → 바로 응답
#                    └─ 없으면 → DB 조회 → Redis에 저장 → 응답
# -> 이렇게 DB를 매번 조회하는 부담을 줄일 수 있음



### 도커(Docker) : 프로그램과 실행에 필요한 환경을 묶어서 실행하는 도구
# -> 프로그램과 필요한 환경을 묶어서 다른 컴퓨터에서도 일관된 환경으로 실행하도록 도와줌 
# Dockerfile → 이미지 → 컨테이너
# (설명서)     (실행 패키지)  (실행 공간)
# ex) 직접 만든 파이썬 프로그램을 실행하려면 :
# 1. Dockerfile 작성: 파이썬 버전, 설치할 라이브러리, 실행할 파일을 지정해요.
# 2. 이미지 만들기: Docker가 설명서를 읽고 실행 패키지를 만들어요.
# 3. 컨테이너 실행: 이미지로 컨테이너를 만들어 프로그램을 실행해요.
# 용어          	    뜻                      	    비유    
# 이미지(Image)	        프로그램과 실행 환경을 담은 패키지	    붕어빵 틀
# 컨테이너(Container)	 이미지를 바탕으로 만든 실행 공간	    틀에서 만든 붕어빵
# -> 하나의 이미지로 여러 컨테이너를 만들 수 있음 
# -> Redis도 컴퓨터에 직접 설치하는 대신 Docker로 실행할 수 있음 
# -> Redis는 데이터를 저장하는 프로그램이고, Docker는 Redis 같은 프로그램을 쉽게 실행하고 관리하는 도구
# Docker
# └─ Redis 컨테이너 실행
#         ↑
#    main.py에서 접속

# 왜 쓰나요?
# 파이썬 프로그램을 다른 컴퓨터로 옮기면 이런 문제가 생길 수 있죠.
# - 파이썬 버전이 다름
# - 필요한 라이브러리가 없음
# - 설정이 달라서 실행이 안 됨